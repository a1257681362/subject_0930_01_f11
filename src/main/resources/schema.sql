-- ============================================================================
-- 车载温度探头校准凭证管理（V3 / cold-chain-3）
-- 设计要点：
-- 1. 温度探头建档登记序列号（库内唯一）、量程上下限、校准机构与当前校准有效期；
--    t_cc_temp_probe 保存探头主档（含“当前凭证ID”冗余便于展示），校准历史全部在
--    t_cc_probe_cert 只追加——凭证只有 VALID 与作废状态，作废不改原行、不删除文件，
--    新一轮校准通过“上传新凭证”表达；探头本身 ACTIVE/REVOKED，不随证书轮换删行。
-- 2. 证书上传即对文件内容计算 SHA-256 摘要落库；下载、作废动作逐次写 t_cc_op_log
--    （实体类型 PROBE / CERT，动作 CERT_UPLOAD/CERT_DOWNLOAD/CERT_VOID），
--    同时在 t_cc_probe_cert.last_download_time 记录最近下载时间（仅下载记账，非原始数据修改）。
-- 3. 车辆当前绑定在 t_cc_vehicle_probe：每车至多一条当前绑定（vehicle_id 唯一）；
