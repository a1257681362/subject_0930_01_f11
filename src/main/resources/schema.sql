    closed_from   TIMESTAMP,                               -- 临时闭馆起点（CLOSED 区间闭馆时用）
    closed_to     TIMESTAMP,                               -- 临时闭馆终点（CLOSED 区间闭馆时用）
    holiday_name  VARCHAR(128) NOT NULL,                  -- 节假日名称/闭馆事由
    -- 生效状态：ACTIVE 当前参与 ETA 判定 / VOID 已作废（仅状态，原始行保留；冻结行不能作废）
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    -- 是否曾参与已生效时窗结论（派车承诺或生效改期 ETA 引用过）：TRUE 则永久冻结，禁改禁撤
    frozen        BOOLEAN      NOT NULL DEFAULT FALSE,
    frozen_time   TIMESTAMP,
    frozen_by     BIGINT,
    frozen_batch_id BIGINT,                                -- 首次冻结该规则的批次（追溯锚点）
    void_reason   VARCHAR(255),
    void_time     TIMESTAMP,
    create_by     BIGINT,
    create_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by     BIGINT,
    update_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cc_holiday_kind CHECK (rule_kind IN ('HOLIDAY', 'CLOSED'))
);
