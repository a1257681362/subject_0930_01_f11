-- ============================================================================
-- 冷链承运商报价比选与锁价（V8 / cold-chain-8）
-- 设计要点：
-- 1. 承运商独立主档（t_cc_carrier），与 t_cc_vehicle.carrier_name 自由文本解耦；
--    车辆登记可携带 carrier_id 指向主档，报价/锁价/结算追溯以主档为准。
-- 2. 一次询价 = 一个报价批次（t_cc_quote_batch）：固化路线/温区/箱型/服务等级/计划发运时间，
--    状态 OPEN -> CLOSED（截止）-> EXPIRED（过期，定时或懒标记）。并行报价：多家承运商在
--    同一批次内各提交一张报价单（t_cc_carrier_quote），互不影响、可在截止前各自修订
--    （报价单只追加修订行，旧版本置 SUPERSEDED）。
-- 3. 报价过期后不能被新批次引用：锁价（创建锁价单）时再次校验报价批次仍在有效期
--    （now < quote_expire_time 且状态未关闭/过期），已过期报价一律拒绝；新建报价批次时
--    禁止把报价维度指向已过期批次（维度快照只从批次头复制，不允许引用旧报价行）。
-- 4. 一个锁价单只能选一个有效方案：t_cc_locked_price 对 quote_batch_id 建唯一约束，
--    中选报价被 LOCKED、其余落选方案置 REJECTED，批次转 CLOSED；锁价瞬间把报价的
--    路线/温区/箱型/服务等级/承运商/基础运费/附加费/税率/有效期逐字段快照到锁价单，
--    此后报价修订或过期都与锁价单脱钩。
-- 5. 金额必须拆出附加费与税率：基础运费 base_amount + 附加费明细（t_cc_quote_surcharge，
--    逐行 INSERT-only）+ 税率 tax_rate；系统按 基础+附加费 小计与 税额=含税-小计 统一口径
--    重算并校验合计，禁止只给一个一口价总价。锁价时附加费逐行快照（snapshot=TRUE）。
-- 6. 人工改价必须经过审批并保留原始报价：锁价后金额不允许直接改，只能发起“改价申请”
--    （t_cc_quote_adjust_approval），落 PENDING，由有权限的审批岗同意后才生效；
--    申请单留存改价前后全部金额字段与原始报价ID，原始报价行/锁价快照永不覆盖。
-- 7. 锁价单反查：t_cc_transport_batch 冗余 locked_price_id，锁价单持 quote_id/quote_batch_id/
--    carrier_id；反查接口沿 锁价单 -> 中选原报价（含历版）-> 报价批次 -> 承运商 -> 改价审批链
--    一路定位原单、各环节处理人与异常原因（过期失效/落选/改价被驳回等）。
-- ============================================================================

