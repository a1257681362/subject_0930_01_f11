-- ============================================================================
-- 送达时窗管理（V10 / cold-chain-10）
-- 设计要点：
-- 1. 收货机构主档（t_cc_receive_org）：机构名库内唯一，与运输批次 receiver_org 自由文本
--    对应；可在此维护"谁在什么时间能收货"。机构主档只维护当前时窗规则版本指针。
-- 2. 时窗规则按版本管理（t_cc_delivery_window_rule + t_cc_delivery_window_slot）：
--    每个收货机构一条当前版本；调整只能生成新版本（草稿 -> 发布热替换，旧版本置
--    SUPERSEDED，版本行与工作日区间行永不修改）；版本内按星期几（1=周一 ... 7=周日）
--    维护若干可接收区间（HH:mm-HH:mm），同一工作日内区间不得重叠。
-- 3. 节假日与临时闭馆独立保存（t_cc_holiday_rule）：与工作日区间分开，分两类——
--    HOLIDAY 法定/机构节假日（整日不可接收，含年份、日期、名称）和 CLOSED 临时闭馆
--    （具体某一天/某段时间闭馆，可给闭馆原因）；两类规则独立追加，不随规则版本走。
-- 4. 承诺到达时间（committed_arrival_time）派车时按"计划发运时间+运输时长"结合当时生效
--    规则与节假日表解析并固化到批次，只写一次，此后任何改期都不动它；改期只更新预计
--    到达（estimated_arrival_time），并逐次追加 t_cc_batch_reschedule 历史，可追查。
-- 5. 批次新增"装车"状态（LOADING，派车之后、发运之前的一个节点）：已进入装车状态的
--    批次改期必须走审批；未装车（DISPATCHED）可调度直接改期（仍留痕、重算 ETA）。
-- 6. 改期单（t_cc_batch_reschedule）：一次改期一张单：DISPATCHED 直接 AUTO 生效；
--    LOADING 及以后（在途含 EXCEPTION）落 PENDING 审批，同意后才应用，驳回不变。
--    审批期间原始承诺/预计列不动，待同意事务内一次性更新。
-- 7. 受影响分析（t_cc_reschedule_impact）：改期时逐条记录受影响的"温控区间"（路线分段
--    快照/档案温区，含段序号、允许温区、责任人）、"承运通知"（需重新通知的承运商/
--    关联报价/锁价/车辆/驾驶员）、"待办责任人们"（收货岗/调度/质量复核等需跟进的人）。
-- 8. 承运通知（t_cc_carrier_notify_log）与待办（t_cc_reschedule_todo）：改期生效（含
--    审批同意）后生成；通知按 webhook 投递，失败留原因可手动重试（参照 V6 通知口径）；
--    待办只有 PENDING/DONE 两态，确认只写确认字段，事实保留可查。
-- 9. 节假日旧结论冻结：一条节假日/临时闭馆规则一旦参与过任一已生效时窗结论（派车承诺
--    或已生效改期 ETA 的解析快照引用），即 frozen=TRUE，此后不可修改、不可撤销/删除，
--    只能新增规则来调整；规则版本调整同理只能出新版本，不能改动节假日旧结论。
-- ============================================================================

